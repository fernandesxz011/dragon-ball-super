import { AdditiveBlending, DataTexture, LinearFilter, Matrix4, Mesh, NoColorSpace, PlaneGeometry, ShaderMaterial, Vector2, Vector4 } from 'three'
import { characterAuraShapes } from './character-aura-paths'
import { auraDissolve, maxProtectedRects, type EffectQuality } from './config'
import { energyMaskShader, type EnergyUniforms } from './particles'

type AuraShape = (typeof characterAuraShapes)[string]

export function createAuraControl(shape: AuraShape, quality: EffectQuality) {
  const ratio = Math.min(1, quality.auraTextureSize / Math.max(shape.width, shape.height))
  const width = Math.max(1, Math.round(shape.width * ratio))
  const height = Math.max(1, Math.round(shape.height * ratio))
  const body = document.createElement('canvas')
  const work = document.createElement('canvas')
  body.width = work.width = width
  body.height = work.height = height
  try {
    const bodyContext = body.getContext('2d', { willReadFrequently: true })
    const workContext = work.getContext('2d', { willReadFrequently: true })
    if (!bodyContext || !workContext) throw new Error('Aura control canvas unavailable')
    bodyContext.scale(width / shape.width, height / shape.height)
    bodyContext.fillStyle = '#fff'
    shape.paths.forEach((path) => bodyContext.fill(new Path2D(path), 'evenodd'))
    const filled = bodyContext.getImageData(0, 0, width, height).data
    function blurred(radius: number) {
      workContext!.clearRect(0, 0, width, height)
      workContext!.filter = `blur(${radius}px)`
      workContext!.drawImage(body, 0, 0)
      return workContext!.getImageData(0, 0, width, height).data
    }
    const wide = blurred(quality.auraWideBlur)
    const rim = blurred(quality.auraRimBlur)
    workContext.clearRect(0, 0, width, height)
    workContext.filter = 'blur(2px)'
    workContext.scale(width / shape.width, height / shape.height)
    workContext.fillStyle = '#fff'
    shape.faces.forEach(([x, y, faceWidth, faceHeight]) => workContext.fillRect(x - 5, y - 5, faceWidth + 10, faceHeight + 10))
    // Ambiguous silhouette/occlusion areas suppress only aura. They do not
    // claim that background pixels belong to a separately cut-out character.
    workContext.filter = 'blur(5px)'
    shape.occlusions?.forEach((path) => workContext.fill(new Path2D(path), 'evenodd'))
    const faces = workContext.getImageData(0, 0, width, height).data
    const packed = new Uint8Array(width * height * 4)
    for (let offset = 0; offset < packed.length; offset += 4) {
      packed[offset] = filled[offset + 3]
      packed[offset + 1] = wide[offset + 3]
      packed[offset + 2] = rim[offset + 3]
      packed[offset + 3] = faces[offset + 3]
    }
    // Upload raw channels: an alpha-zero face mask must not premultiply away
    // the RGB body/contour masks generated by the temporary canvases.
    const texture = new DataTexture(packed, width, height)
    texture.name = 'character-aura-control'
    texture.colorSpace = NoColorSpace
    texture.flipY = false
    texture.generateMipmaps = false
    texture.minFilter = texture.magFilter = LinearFilter
    texture.needsUpdate = true
    return texture
  } finally {
    body.width = body.height = work.width = work.height = 1
  }
}

export function createCharacterAura(shared: EnergyUniforms, quality: EffectQuality) {
  const geometry = new PlaneGeometry(2, 2)
  const controls = new Map<string, DataTexture>()
  const failed = new Set<string>()
  const uniforms = {
    ...shared,
    // Aura protects HTML independently: the field's broad face/hair ROIs
    // would hide the very silhouette this control texture is meant to trace.
    uRects: { value: Array.from({ length: maxProtectedRects }, () => new Vector4()) },
    uRectCount: { value: 0 },
    uControl: { value: null as DataTexture | null },
    uArtMatrix: { value: new Matrix4() },
    uImage: { value: new Vector4(0, 0, 1, 1) },
    uFrame: { value: new Vector4(0, 0, 1, 1) },
    uSurfaceCenter: { value: new Vector2() },
    uTexel: { value: new Vector2(1, 1) },
    uAuraOpacity: { value: 0 },
    uDissolve: { value: new Vector2(0.86, 1) },
    uStrength: { value: quality.auraStrength },
  }
  const material = new ShaderMaterial({
    name: 'character-silhouette-aura-material',
    uniforms, transparent: true, depthWrite: false, depthTest: false,
    blending: AdditiveBlending, toneMapped: false,
    vertexShader: `
      uniform vec2 uViewport, uSurfaceCenter;
      uniform vec4 uImage;
      uniform mat4 uArtMatrix;
      varying vec2 vNativeUv;
      void main() {
        vNativeUv = vec2(uv.x, 1.0 - uv.y);
        vec2 imagePixel = mix(uImage.xy, uImage.zw, vNativeUv);
        vec4 projected = uArtMatrix * vec4(imagePixel - uSurfaceCenter, 0.0, 1.0);
        // Keep homogeneous W: this is the CSS perspective around the same
        // transform-origin, rather than a separately estimated WebGL tilt.
        gl_Position = vec4(
          projected.x * 2.0 / uViewport.x + (uSurfaceCenter.x * 2.0 / uViewport.x - 1.0) * projected.w,
          -projected.y * 2.0 / uViewport.y + (1.0 - uSurfaceCenter.y * 2.0 / uViewport.y) * projected.w,
          0.0, projected.w);
      }
    `,
    fragmentShader: `
      uniform sampler2D uControl;
      uniform float uTime, uDpr, uIntensity, uMaskFeather, uAuraOpacity, uStrength;
      uniform vec2 uViewport, uTexel, uDissolve;
      uniform vec4 uFrame;
      uniform vec3 uPrimary, uSecondary;
      uniform int uRectCount;
      uniform vec4 uRects[${maxProtectedRects}];
      varying vec2 vNativeUv;
      ${energyMaskShader}
      void main() {
        vec2 screen = vec2(gl_FragCoord.x / uDpr, uViewport.y - gl_FragCoord.y / uDpr);
        if (any(lessThan(screen, uFrame.xy)) || any(greaterThan(screen, uFrame.zw))) discard;
        vec4 control = texture2D(uControl, vNativeUv);
        if (control.r > 0.02) discard;
        if (max(control.g, control.b) < 0.002) discard;
        float visibility = contentVisibility(screen) * (1.0 - smoothstep(0.0, 0.2, control.a));
        if (visibility < 0.001) discard;
        vec2 drift = vec2(sin(vNativeUv.y * 24.0 - uTime * 1.3), cos(vNativeUv.x * 21.0 + uTime)) * uTexel * 1.8;
        vec4 flowControl = texture2D(uControl, vNativeUv + drift);
        float glow = max(control.g, flowControl.g * 0.88);
        float rim = pow(max(control.b, 0.0), 0.9);
        float flow = 0.74 + 0.26 * pow(sin(vNativeUv.y * 23.0 + vNativeUv.x * 15.0 - uTime * 1.5), 2.0);
        float nativeEdge = min(min(vNativeUv.x, 1.0 - vNativeUv.x), min(vNativeUv.y, 1.0 - vNativeUv.y));
        float edgeFade = smoothstep(0.0, max(uTexel.x, uTexel.y) * 7.0, nativeEdge);
        edgeFade *= 1.0 - smoothstep(uDissolve.x, uDissolve.y, vNativeUv.y);
        vec3 color = mix(uPrimary, uSecondary, smoothstep(0.45, 0.9, vNativeUv.x));
        color = mix(color, vec3(0.88, 0.96, 1.0), min(0.45, rim * 1.25));
        float alpha = min(0.78, (rim * 1.3 + glow * 0.85) * flow * uIntensity * uStrength);
        gl_FragColor = vec4(color, alpha * visibility * edgeFade * uAuraOpacity);
        #include <colorspace_fragment>
      }
    `,
  })
  const mesh = new Mesh(geometry, material)
  mesh.name = 'character-silhouette-aura'
  mesh.frustumCulled = false
  mesh.renderOrder = -3
  mesh.visible = false
  let disposed = false
  let selectedId: string | undefined
  return {
    mesh, uniforms,
    get textureCount() { return controls.size },
    select(id: string) {
      if (disposed || failed.has(id) || !characterAuraShapes[id]) return false
      if (id === selectedId && uniforms.uControl.value) return true
      try {
        let texture = controls.get(id)
        if (!texture) {
          texture = createAuraControl(characterAuraShapes[id], quality)
          controls.set(id, texture)
        }
        uniforms.uControl.value = texture
        uniforms.uTexel.value.set(1 / texture.image.width, 1 / texture.image.height)
        const dissolve = auraDissolve[id] ?? [0.86, 1]
        uniforms.uDissolve.value.set(dissolve[0], dissolve[1])
        selectedId = id
        return true
      } catch {
        failed.add(id)
        mesh.visible = false
        return false
      }
    },
    dispose() {
      if (disposed) return
      disposed = true
      mesh.removeFromParent()
      geometry.dispose()
      material.dispose()
      controls.forEach((texture) => texture.dispose())
      controls.clear()
      failed.clear()
      uniforms.uControl.value = null
      selectedId = undefined
    },
  }
}
